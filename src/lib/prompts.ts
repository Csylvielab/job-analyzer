/**
 * 岗位分析助手的 Prompt 模板
 */

export interface SearchResult {
  category: string;
  query: string;
  results: string[];
  sources: string[];
}

export interface JobAnalysisInput {
  company: string;
  position: string;
  jd?: string;
  searchResults: SearchResult[];
}

